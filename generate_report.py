def set_cell_borders(cell):
    tc_pr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for border in ('top', 'left', 'bottom', 'right'):
        el = OxmlElement(f'w:{border}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '4')
        el.set(qn('w:color'), '000000')
        tcBorders.append(el)
    tc_pr.append(tcBorders)


def add_heading(doc, text, level=1, align=None):
    h = doc.add_heading(text, level=level)
    if align is not None:
        h.alignment = align
    for run in h.runs:
        run.font.name = 'Times New Roman'
        run.font.color.rgb = RGBColor(0, 0, 0)
    return h


def add_par(doc, text, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
            size=12, first_line=True):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    if first_line:
        pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(0)
    pf.line_spacing = 1.15
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    return p


def add_bullet(doc, text, size=12):
    p = doc.add_paragraph(style='List Bullet')
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.space_after = Pt(0)
    pf.line_spacing = 1.15
    run = p.runs[0] if p.runs else p.add_run('')
    run.text = text
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    return p


def fill_table_cell(cell, text, bold=False, size=10, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_after = Pt(0)
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.bold = bold
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    set_cell_borders(cell)


